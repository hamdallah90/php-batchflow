int main(void)
{
	const uint64_t key[2] = { UINT64_C(0x0706050403020100), UINT64_C(0x0f0e0d0c0b0a0908) };
	static const int64_t ints[] = { 0, 1, -1, INT64_MIN, INT64_MAX, 0x0706050403020100, 1000003 };
	uint8_t msg[64];
	int bad = 0;
	size_t splits = 0;

	for (int t = 0; t < 64; t++) {
		uint64_t want = 0;

		msg[t] = (uint8_t)t;
		for (int b = 7; b >= 0; b--) {
			want = (want << 8) | VECTORS[t][b];
		}
		if (bf_siphash13(key, msg, (size_t)t) != want) {
			fprintf(stderr, "vector %d: got %016" PRIx64 " want %016" PRIx64 "\n", t, bf_siphash13(key, msg, (size_t)t), want);
			bad++;
		}
		/* The incremental form over every split of the message into three updates, empty ones included. */
		for (int a = 0; a <= t; a++) {
			for (int b = a; b <= t; b++) {
				bf_sip s;

				bf_sip_init(&s, key);
				bf_sip_update(&s, msg, (size_t)a);
				bf_sip_update(&s, msg + a, (size_t)(b - a));
				bf_sip_update(&s, msg + b, (size_t)(t - b));
				splits++;
				if (bf_sip_final(&s) != want) {
					fprintf(stderr, "vector %d split %d/%d: incremental differs\n", t, a, b);
					bad++;
				}
			}
		}
	}
	for (size_t i = 0; i < sizeof(ints) / sizeof(ints[0]); i++) {
		uint8_t le[8];
		uint64_t u = (uint64_t)ints[i];

		for (int b = 0; b < 8; b++) {
			le[b] = (uint8_t)(u >> (8 * b));
		}
		if (bf_siphash13_u64(key, u) != bf_siphash13(key, le, 8)) {
			fprintf(stderr, "int form differs for %" PRId64 "\n", ints[i]);
			bad++;
		}
	}
	printf("siphash13: 64 vectors, %zu incremental splits, %zu int forms, %d failures\n", splits, sizeof(ints) / sizeof(ints[0]), bad);
	return bad != 0;
}
